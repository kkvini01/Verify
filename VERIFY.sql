GO
USE VERIFY;
GO

CREATE TABLE USUARIO
(
	ID_USUARIO INT IDENTITY(1, 1) PRIMARY KEY 
	,NOME_COMPLETO VARCHAR(255) NOT NULL
	,NOME_USUARIO VARCHAR(255) NOT NULL
	,EMAIL VARCHAR(255) NOT NULL
	,SENHA VARCHAR(255) NOT NULL
	,DATA_NASCIMENTO DATE NOT NULL
	,TIPO_PLANO VARCHAR(255) NOT NULL
);
GO

CREATE TABLE ARTISTA
(
	ID_ARTISTA INT IDENTITY(1, 1) PRIMARY KEY 
	,NOME_ARTISTICO VARCHAR(255) NOT NULL
	,NOME_REAL VARCHAR(255) NOT NULL
	,BIOGRAFIA VARCHAR(255) NOT NULL
	,GENERO_PRINCIPAL VARCHAR(255) NOT NULL
	,DATA_NASCIMENTO DATE NOT NULL
	,DATA_INICIO_CARREIRA DATE NOT NULL
);
GO

CREATE TABLE ALBUM
(
	ID_ALBUM INT IDENTITY(1, 1) PRIMARY KEY 
	,ID_ARTISTA INT
	,NOME_ALBUM VARCHAR(255) NOT NULL
	,DATA_LANCAMENTO_ALBUM DATE NOT NULL
	,GRAVADORA VARCHAR(255) NOT NULL
	,CAPA_URL VARCHAR(300) NOT NULL
	,DURACAO_TOTAL VARCHAR(255) NOT NULL
	,TIPO_ALBUM VARCHAR(255) NOT NULL
	,NUMERO_FAIXAS INT NOT NULL

	CONSTRAINT FK_ALBUM_ARTISTA FOREIGN KEY (ID_ARTISTA) 
	REFERENCES ARTISTA(ID_ARTISTA)
);
GO

CREATE TABLE MUSICA
(
	ID_MUSICA INT IDENTITY(1, 1) PRIMARY KEY 
	,ID_ARTISTA INT
	,ID_ALBUM INT
	,TITULO_MUSICA VARCHAR(255) NOT NULL
	,DURACAO_MUSICA VARCHAR(255) NOT NULL
	,DATA_LANCAMENTO_MUSICA DATE NOT NULL
	,GENERO_MUSICAL VARCHAR(255) NOT NULL
	,COMPOSITOR VARCHAR(255) NOT NULL
	,NUMERO_REPRODUCOES INT NOT NULL

	CONSTRAINT FK_MUSICA_ARTISTA FOREIGN KEY (ID_ARTISTA) 
	REFERENCES ARTISTA(ID_ARTISTA)
	,CONSTRAINT FK_MUSICA_ALBUM FOREIGN KEY (ID_ALBUM) 
	REFERENCES ALBUM(ID_ALBUM)
);
GO

CREATE TABLE PLAYLIST
(
	ID_PLAYLIST INT IDENTITY(1, 1) PRIMARY KEY
	,ID_USUARIO INT
	,NOME_PLAYLIST VARCHAR(255) NOT NULL
	,DESCRICAO VARCHAR(255) NOT NULL
	,DAT_CRIACAO DATE NOT NULL
	,DAT_ATUALIZACAO DATE NOT NULL
	,PUBLICA INT NOT NULL
	,QTD_LIKES INT NOT NULL
	
	CONSTRAINT FK_PLAYLIST_USUARIO FOREIGN KEY (ID_USUARIO) 
	REFERENCES USUARIO(ID_USUARIO)
);
GO

CREATE TABLE PLAYLIST_MUSICA
(
	ID_PLAYLIST INT NOT NULL
	,ID_MUSICA INT NOT NULL
	
	,CONSTRAINT PK_PLAYLIST_MUSICA PRIMARY KEY (ID_PLAYLIST, ID_MUSICA)
	,CONSTRAINT FK_PM_PLAYLIST FOREIGN KEY (ID_PLAYLIST) REFERENCES PLAYLIST(ID_PLAYLIST)
	,CONSTRAINT FK_PM_MUSICA FOREIGN KEY (ID_MUSICA) REFERENCES MUSICA(ID_MUSICA)
);
